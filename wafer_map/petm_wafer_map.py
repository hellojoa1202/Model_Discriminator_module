class WaferDataset(Dataset):
    def __init__(self, df: pd.DataFrame, transform=None):
        self.df = df
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        img_array = row["waferMap"]  # 이미 numpy array일 것
        label = int(row["failureNum"])

        # [H, W] → [H, W, 3] (1채널을 3채널로 복제)
        if isinstance(img_array, np.ndarray) and img_array.ndim == 2:
            img_array = np.stack([img_array]*3, axis=-1)  # (H, W, 3)

        img = Image.fromarray(img_array.astype(np.uint8))  # numpy → PIL 이미지

        if self.transform:
            img = self.transform(img)

        return img, label

