# 라벨 처리 함수
def clean_split_label(x):
    if isinstance(x, (list, np.ndarray)):
        if len(x) == 0:
            return None
        if isinstance(x[0], (list, np.ndarray)):
            return str(x[0][0]).strip() if len(x[0]) > 0 else None
        elif isinstance(x[0], str):
            return x[0].strip()
    elif isinstance(x, str):
        return x.strip()
    return None

def clean_failure_type(x):
    if isinstance(x, (list, np.ndarray)):
        if len(x) == 0:
            return None
        if isinstance(x[0], str):
            return x[0].strip()
    elif isinstance(x, str):
        return x.strip()
    return None

